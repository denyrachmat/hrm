        function format(d) {
            return '<table cellpadding="5" cellspacing="0" border="0" style="padding-left:50px;">' +
                JSON.parse(d.earnings).map((e) => {
                    return `
                        <tr>
                            <td>${e.name}</td>
                            <td>:</td>
                            <td>${e.amount}</td>
                        </tr>
                    `
                })
            '</table>';
        }

        $('#data-table').on('click', 'tbody td.dt-control', function() {
